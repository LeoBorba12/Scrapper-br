// Cache rápido de busca por apelidos / slugs normalizados
const ALIAS_INDEX = {};
for (const [canonical, data] of Object.entries(CLUB_REGISTRY)) {
  ALIAS_INDEX[canonical.toLowerCase()] = canonical;
  for (const alias of (data.aliases || [])) {
    ALIAS_INDEX[alias.toLowerCase()] = canonical;
  }
}

/**
 * Remove acentos e caracteres especiais para busca tolerante
 */
export function normalizeClubName(nome) {
  if (!nome || typeof nome !== 'string') return '';
  return nome
    .trim()
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9\s-]/g, '');
}

/**
 * Recupera metadados do clube (escudo, sigla, cores) com fallback inteligente
 */
export function getClubInfo(nome) {
  if (!nome || typeof nome !== 'string') {
    return {
      fullName: 'Clube',
      sigla: 'CLU',
      bg: '#2A2E39',
      text: '#FFFFFF',
      badge: ''
    };
  }

  const raw = nome.trim();
  const lower = raw.toLowerCase();

  // 1. Busca direta ou por alias
  if (CLUB_REGISTRY[raw]) return CLUB_REGISTRY[raw];
  if (ALIAS_INDEX[lower]) return CLUB_REGISTRY[ALIAS_INDEX[lower]];

  // 2. Busca normalizada sem acentos
  const norm = normalizeClubName(raw);
  for (const [alias, canonical] of Object.entries(ALIAS_INDEX)) {
    if (normalizeClubName(alias) === norm) {
      return CLUB_REGISTRY[canonical];
    }
  }

  // 3. Busca por substring (ex: 'Flamengo (RJ)' -> 'Flamengo')
  for (const [canonical, data] of Object.entries(CLUB_REGISTRY)) {
    const cNorm = normalizeClubName(canonical);
    if (norm.includes(cNorm) || cNorm.includes(norm)) {
      return data;
    }
  }

  // 4. Fallback gerador de monograma neutro
  const palavras = raw.split(/\s+/).filter(Boolean);
  let sigla = 'CLU';
  if (palavras.length === 1) {
    sigla = palavras[0].slice(0, 3).toUpperCase();
  } else if (palavras.length === 2) {
    sigla = (palavras[0][0] + palavras[1].slice(0, 2)).toUpperCase();
  } else {
    sigla = (palavras[0][0] + palavras[1][0] + palavras[2][0]).toUpperCase();
  }

  return {
    fullName: raw,
    sigla,
    bg: '#2A2E39',
    text: '#FFFFFF',
    badge: ''
  };
}

